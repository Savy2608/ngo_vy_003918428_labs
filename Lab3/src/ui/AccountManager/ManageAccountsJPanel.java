    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String keyword = txtSearch.getText().toLowerCase();
        DefaultTableModel model = (DefaultTableModel) tblAccounts.getModel();
        model.setRowCount(0);
        for (Account a : accountDirectory.getAccounts()) {
            if (a.getBankName().toLowerCase().contains(keyword) ||
                    a.getAccountNumber().toLowerCase().contains(keyword) ||
                    a.getRoutingNumber().toLowerCase().contains(keyword)) {
                model.addRow(new Object[]{
                    a.getBankName(), a.getRoutingNumber(),
                    a.getAccountNumber(), a.getBalance()
                });
            }
        }

    }//GEN-LAST:event_btnSearchActionPerformed


