    private void btnViewDetailsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewDetailsActionPerformed
        // TODO add your handling code here:
        int row = tblAccounts.getSelectedRow();
        if (row == -1) {
          javax.swing.JOptionPane.showMessageDialog(this, "Please select an account.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
          return;    
    }//GEN-LAST:event_btnViewDetailsActionPerformed
        Account a = accountDirectory.getAccounts().get(row);
        ViewAccountJPanel panel = new ViewAccountJPanel(userProcessContainer, accountDirectory, a);
        userProcessContainer.add("ViewAccountJPanel", panel);
        java.awt.CardLayout layout = (java.awt.CardLayout) userProcessContainer.getLayout();
        layout.next(userProcessContainer);
    }
    

    private void btnDeleteAccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteAccountActionPerformed
        // TODO add your handling code here:
        int row = tblAccounts.getSelectedRow();
        if (row == -1) {
             javax.swing.JOptionPane.showMessageDialog(this, "Please select an account.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
              return;
        }
        Account a = accountDirectory.getAccounts().get(row);
        accountDirectory.deleteAccount(a);
        populateTable();
              
    }//GEN-LAST:event_btnDeleteAccountActionPerformed

